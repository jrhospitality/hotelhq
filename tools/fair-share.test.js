test("snapshot rows match the import table and sample data stays unlabeled as a live feed", () => {
  const model = fsmod.buildDemo(NOW);
  const rows = fsmod.snapshotRows(model);
  assert.equal(rows.length, 6);
  const row = rows.find((item) => item.hotel === "MSPWE" && item.period === "t7");
  assert.equal(row.source, "sample");
  assert.equal(row.currency, "USD");
  assert.equal(row.period_end, "2026-11-09");
  assert.equal(row.occ, 78.4);
  assert.equal(row.occ_comp, 74.1);
  assert.equal(row.adr_ly, 124.10);
  assert.equal(row.revpar_comp_ly, 93.73);
  assert.equal(row.comp_set_label, "Sample competitive set");
  const slot = fsmod.importSlot("MSPWE", "daystar", "2026-11-09", "IHG DaySTAR still pending");
  assert.equal(slot.status, "pending");
  assert.equal(slot.source, "daystar");
  assert.equal(fsmod.importSlot("MSPWE", "sample", "2026-11-09", ""), null);
  assert.equal(fsmod.importSlot("NOPE", "str", "2026-11-09", ""), null);
  const saved = fsmod.applySaved(model, {
    v: 1,
    rows: [{ hotel: "MSPMS", period: "t28", source: "str", occ: 70.2, occ_comp: 70.2, comp_set_label: "Sample competitive set" }]
  });
  assert.equal(saved.hotels.MSPMS.t28.occ, 70.2);
  assert.equal(saved.hotels.MSPMS.source, "str");
  assert.equal(saved.hotels.MSPWE.t7.occ, 78.4);
  const blob = JSON.stringify(model) + fsmod.pageHtml(model, corp, { lang: "en", portfolio: true });
  assert.equal(/@/.test(blob), false);
  assert.equal(/\b\d{3}[-.\s]\d{3}[-.\s]\d{4}\b/.test(blob), false);
  assert.equal(/Bhakta|Uselman/i.test(blob), false);
});

test("the migration stores later imports and does not publish sample guests", () => {
  const root = path.join(__dirname, "..");
  const sql = fs.readFileSync(path.join(root, "supabase/migrations/20261116_fair_share_and_guest_chats.sql"), "utf8");
  const html = fs.readFileSync(path.join(root, "index.html"), "utf8");
  const sw = fs.readFileSync(path.join(root, "sw.js"), "utf8");
  const src = fs.readFileSync(path.join(root, "fair-share.js"), "utf8");
  assert.ok(html.indexOf('src="glance-home.js"') < html.indexOf('src="fair-share.js"'));
  assert.match(sw, /\.\/fair-share\.js/);
  assert.match(sw, /hotelhq-shell-v23/);
  assert.match(sql, /fair_share_snapshots/);
  assert.match(sql, /fair_share_imports/);
  assert.match(sql, /source in \('sample', 'str', 'daystar', 'mint', 'hilton', 'manual'\)/);
  assert.match(sql, /period in \('t7', 't28'\)/);
  assert.match(sql, /private\.fair_share_allowed/);
  assert.match(sql, /'gm'/);
  assert.match(sql, /private\.is_above\(\)/);
  assert.match(sql, /'fair_share', 'guest_messages'/);
  assert.match(sql, /November 5, 2026/);
  assert.match(sql, /enable row level security/);
  assert.match(sql, /grant select on table public\.fair_share_snapshots to authenticated/);
  assert.doesNotMatch(sql, /grant insert/i);
  assert.doesNotMatch(sql, /drop table/i);
  assert.doesNotMatch(sql, /delete from/i);
  assert.doesNotMatch(sql, /to anon/);
  assert.equal(src.includes("supabaseKey"), false);
  assert.equal(src.includes("sb.from"), false);
  assert.equal(fsmod.demoUi({ mode: "live" }), false);
  assert.equal(fsmod.demoUi({ mode: "demo" }), true);
});
