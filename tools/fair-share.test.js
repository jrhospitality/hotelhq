const fsmod = require("../fair-share.js");
const menus = require("../feature-menus.js");
const hhq = require("../permissions.js");

const NOW = "2026-11-09T18:00:00.000Z";
const gm = { role: "GM", hotel: "MSPWE", name: "Avery Cole" };
const agm = { role: "AGM", hotel: "MSPWE", name: "Blake Morgan" };
const corp = { role: "JR Corporate", hotel: null, name: "Alex Rivera" };
const desk = { role: "Front Desk", hotel: "MSPWE", name: "Jordan Lee" };
const hk = { role: "Housekeeping", hotel: "MSPWE", name: "Grace Patel" };
const hampton = { role: "GM", hotel: "MSPAM", name: "Riley Brooks" };

test("only a GM or corporate login can see fair share, and only their hotels", () => {
  assert.equal(hhq.can("GM", "fairshare.see"), true);
  assert.equal(hhq.can("JR Corporate", "fairshare.see"), true);
  assert.equal(hhq.can("AGM", "fairshare.see"), false);
  assert.equal(hhq.can("Front Desk", "fairshare.see"), false);
  assert.equal(hhq.can("Housekeeping", "fairshare.see"), false);
  assert.deepEqual(fsmod.hotelsFor("GM", "MSPWE"), ["MSPWE"]);
  assert.deepEqual(fsmod.hotelsFor("GM", "MSPAM"), ["MSPAM"]);
  assert.deepEqual(fsmod.hotelsFor("AGM", "MSPWE"), []);
  assert.deepEqual(fsmod.hotelsFor("Front Desk", "MSPWE"), []);
  assert.deepEqual(fsmod.hotelsFor("Housekeeping", "MSPMS"), []);
  assert.deepEqual(fsmod.hotelsFor("JR Corporate", null), ["MSPWE", "MSPAM", "MSPMS"]);
  assert.equal(menus.menuAllows("fshare", "GM", "MSPWE"), true);
  assert.equal(menus.menuAllows("fshare", "Above Property", "MSPMS"), true);
  assert.equal(menus.menuAllows("fshare", "AGM", "MSPWE"), false);
  assert.equal(menus.menuAllows("fshare", "Front Desk", "MSPWE"), false);
  assert.equal(menus.menuAllows("fshare", "GM", "MSPWE", function (_h, feature) { return feature !== "fair_share"; }), false);
});

test("T7 and T28 show hotel, comp set, fair share, and year over year", () => {
  const model = fsmod.buildDemo(NOW);
  assert.equal(model.asOf, "2026-11-09");
  assert.equal(model.feed.connected, false);
  assert.deepEqual(model.feed.sources, ["str", "daystar", "mint", "hilton"]);
  const t7 = fsmod.compare(model, "MSPWE", "t7");
  const occ = t7.find((row) => row.id === "occ");
  const adr = t7.find((row) => row.id === "adr");
  const rev = t7.find((row) => row.id === "revpar");
  assert.equal(occ.value, 78.4);
  assert.equal(occ.comp, 74.1);
  assert.equal(occ.indexValue, 105.8);
  assert.equal(occ.index, "MPI");
  assert.equal(occ.yoy, 4.2);
  assert.equal(adr.indexValue, 96.5);
  assert.equal(adr.index, "ARI");
  assert.equal(adr.yoy, 4.4);
  assert.equal(rev.indexValue, 102.1);
  assert.equal(rev.index, "RGI");
  assert.equal(rev.yoy, 10.3);
  assert.equal(occ.indexYoy, 4.2);
  const t28 = fsmod.compare(model, "MSPWE", "t28");
  assert.equal(t28.find((row) => row.id === "occ").indexValue, 101.9);
  assert.notEqual(t28.find((row) => row.id === "occ").value, occ.value);
  assert.equal(fsmod.compare(model, "MSPAM", "t7").find((row) => row.id === "occ").indexValue, 94.1);
  assert.equal(fsmod.compare(model, "MSPMS", "t7").find((row) => row.id === "revpar").indexValue, 86.5);
  assert.equal(fsmod.toneIndex(105.8), "good");
  assert.equal(fsmod.toneIndex(96.5), "watch");
  assert.equal(fsmod.toneIndex(86.5), "bad");
  assert.equal(fsmod.toneYoy(4.2), "good");
  assert.equal(fsmod.toneYoy(-1.5), "watch");
  assert.equal(fsmod.toneYoy(-4), "bad");
});

