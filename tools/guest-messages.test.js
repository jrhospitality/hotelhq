const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const chats = require("../guest-messages.js");
const menus = require("../feature-menus.js");
const hhq = require("../permissions.js");

const NOW = "2026-11-09T18:00:00.000Z";
const desk = { role: "Front Desk", hotel: "MSPWE", name: "Jordan Lee" };
const agm = { role: "AGM", hotel: "MSPWE", name: "Blake Morgan" };
const gm = { role: "GM", hotel: "MSPWE", name: "Avery Cole" };
const corp = { role: "Above Property", hotel: null, name: "Alex Rivera" };
const hampton = { role: "Front Desk", hotel: "MSPAM", name: "Kim Nguyen" };
const spring = { role: "Front Desk", hotel: "MSPMS", name: "Tess Brown" };
const hk = { role: "Housekeeping", hotel: "MSPWE", name: "Grace Patel" };

test("front desk and AGM can answer their own hotel, and other roles cannot", () => {
  assert.equal(hhq.can("Front Desk", "guestchat.respond"), true);
  assert.equal(hhq.can("AGM", "guestchat.respond"), true);
  assert.equal(hhq.can("GM", "guestchat.respond"), false);
  assert.equal(hhq.can("Above Property", "guestchat.respond"), false);
  assert.equal(hhq.can("Housekeeping", "guestchat.respond"), false);
  assert.equal(hhq.can("GM", "guestchat.count"), true);
  assert.equal(hhq.can("Front Desk", "guestchat.count"), false);
  assert.deepEqual(chats.queueHotels("Front Desk", "MSPWE"), ["MSPWE"]);
  assert.deepEqual(chats.queueHotels("AGM", "MSPAM"), ["MSPAM"]);
  assert.deepEqual(chats.queueHotels("Front Desk", "MSPMS"), ["MSPMS"]);
  assert.deepEqual(chats.queueHotels("GM", "MSPWE"), []);
  assert.deepEqual(chats.queueHotels("Above Property", "MSPWE"), []);
  assert.deepEqual(chats.queueHotels("Housekeeping", "MSPWE"), []);
  assert.deepEqual(chats.countHotels("GM", "MSPMS"), ["MSPMS"]);
  assert.deepEqual(chats.countHotels("AGM", "MSPWE"), []);
  assert.equal(menus.menuAllows("gchat", "Front Desk", "MSPWE"), true);
  assert.equal(menus.menuAllows("gchat", "AGM", "MSPWE"), true);
  assert.equal(menus.menuAllows("gchat", "GM", "MSPWE"), false);
  assert.equal(menus.menuAllows("gchat", "Above Property", "MSPAM"), false);
  assert.equal(menus.menuAllows("gchat", "Housekeeper", "MSPWE"), false);
  assert.equal(menus.menuAllows("gchat", "Front Desk", "MSPWE", function (_h, feature) { return feature !== "guest_messages"; }), false);
});

test("MSPWE front desk sees three waiting chats, the oldest wait, and the source", () => {
  const model = chats.buildDemo(NOW);
  const summary = chats.summaryFor(model, "MSPWE", NOW);
  assert.equal(summary.waiting, 3);
  assert.equal(summary.oldestMinutes, 160);
  assert.deepEqual(summary.sources, ["ihg_chat"]);
  assert.equal(summary.rows[0].room, "214");
  const copy = chats.alertCopy(summary, "en");
  assert.match(copy.head, /3 guest chats need a response/);
  assert.match(copy.oldest, /2 hrs 40 min/);
  assert.equal(copy.source, "Source: IHG guest chat");
  const es = chats.alertCopy(summary, "es");
  assert.match(es.head, /3 chats de huéspedes necesitan respuesta/);
  assert.match(es.oldest, /2 h 40 min/);
  assert.equal(es.source, "Origen: Chat de huésped IHG");
  const html = chats.alertHtml(summary, "en");
  assert.match(html, /id="deskChatAlert"/);
  assert.match(html, /go\('gchat'\)/);
  assert.match(html, /3 guest chats need a response/);
  assert.match(html, /Oldest has waited 2 hrs 40 min/);
  assert.match(html, /Source: IHG guest chat/);
  const page = chats.pageHtml(model, desk, { lang: "en", now: NOW });
  assert.match(page, /data-hotel="MSPWE"/);
  assert.match(page, /Holiday Inn Express Golden Valley/);
  assert.match(page, /Room 214/);
  assert.match(page, /Mark responded/);
  assert.match(page, /Sample message: extra towels/);
  assert.match(page, /EXAMPLE/);
  assert.match(page, /Not a live brand chat/);
  assert.equal(page.includes("MSPAM"), false);
  assert.equal(page.includes("Room 412"), false);
  assert.equal(page.includes("Hilton"), false);
  const agmPage = chats.pageHtml(model, agm, { lang: "es", now: NOW });
  assert.match(agmPage, /Chats de huéspedes/);
  assert.match(agmPage, /Marcar respondido/);
  assert.match(agmPage, /Hab\. 214/);
  assert.match(agmPage, /Chat de huésped IHG/);
  assert.equal(agmPage.includes("MSPAM"), false);
});

test("other hotels stay local, an unknown source is labeled, and an empty queue stays quiet", () => {
  const model = chats.buildDemo(NOW);
  const hamptonSummary = chats.summaryFor(model, "MSPAM", NOW);
  assert.equal(hamptonSummary.waiting, 2);
  assert.equal(hamptonSummary.oldestMinutes, 65);
  assert.deepEqual(hamptonSummary.sources, ["hilton_chat"]);
  assert.equal(chats.alertCopy(hamptonSummary, "en").source, "Source: Hilton guest chat");
  const hamptonPage = chats.pageHtml(model, hampton, { lang: "en", now: NOW });
  assert.match(hamptonPage, /Source unknown/);
  assert.match(hamptonPage, /Room 412/);
  assert.equal(hamptonPage.includes("Room 214"), false);
  assert.equal(hamptonPage.includes("MSPWE"), false);
  const springSummary = chats.summaryFor(model, "MSPMS", NOW);
  assert.equal(springSummary.waiting, 0);
  assert.equal(chats.alertHtml(springSummary, "en"), "");
  const springPage = chats.pageHtml(model, spring, { lang: "en", now: NOW });
  assert.match(springPage, /No guest chats are waiting/);
  assert.match(springPage, /data-hotel="MSPMS"/);
  assert.equal(springPage.includes("Mark responded"), false);
  const esClear = chats.pageHtml(model, spring, { lang: "es", now: NOW });
  assert.match(esClear, /No hay chats de huéspedes en espera/);
  assert.equal(chats.pageHtml(model, gm, { lang: "en", now: NOW }).includes("Mark responded"), false);
  assert.equal(chats.pageHtml(model, corp, { lang: "en", now: NOW }).includes("Room"), false);
  assert.equal(chats.pageHtml(model, hk, { lang: "en", now: NOW }).includes("guest chat"), false);
  const count = chats.countHtml(chats.summaryFor(model, "MSPWE", NOW), "en");
  assert.match(count, /id="gmChatCount"/);
  assert.match(count, /3 guest chats waiting/);
  assert.match(count, /2 hrs 40 min/);
  assert.equal(count.includes("go('gchat')"), false);
  assert.equal(chats.countHtml(springSummary, "en"), "");
});

test("marking a chat responded drops it from the waiting list and stays on this hotel", () => {
  const model = chats.buildDemo(NOW);
  const denied = chats.respond(model, "msg-mspwe-towels", gm, NOW);
  assert.equal(denied.ok, false);
  assert.equal(denied.error, "role");
  const other = chats.respond(model, "msg-mspwe-towels", hampton, NOW);
  assert.equal(other.ok, false);
  assert.equal(other.error, "hotel");
  const done = chats.respond(model, "msg-mspwe-towels", desk, NOW);
  assert.equal(done.ok, true);
  assert.equal(chats.summaryFor(done.model, "MSPWE", NOW).waiting, 2);
  assert.equal(chats.summaryFor(model, "MSPWE", NOW).waiting, 3);
  const page = chats.pageHtml(done.model, desk, { lang: "en", now: NOW });
  assert.match(page, /Responded · Jordan Lee/);
  assert.equal((page.match(/Mark responded/g) || []).length, 2);
  const again = chats.respond(done.model, "msg-mspwe-towels", agm, "2026-11-09T19:00:00.000Z");
  assert.equal(again.model.messages.find((row) => row.id === "msg-mspwe-towels").respondedAt, NOW);
  const overlay = chats.userOverlay(done.model, model);
  assert.equal(overlay.responded.length, 1);
  const restored = chats.applySaved(chats.buildDemo(NOW), overlay);
  assert.equal(chats.summaryFor(restored, "MSPWE", NOW).waiting, 2);
  const row = chats.messageRow(done.model.messages.find((item) => item.id === "msg-mspwe-towels"));
  assert.equal(row.hotel, "MSPWE");
  assert.equal(row.source, "ihg_chat");
  assert.equal(row.preview_en.includes("@"), false);
  assert.equal(row.external_id, "");
  const blob = JSON.stringify(chats.buildDemo(NOW));
  assert.equal(/@/.test(blob), false);
  assert.equal(/\b\d{3}[-.\s]\d{3}[-.\s]\d{4}\b/.test(blob), false);
  assert.equal(/Bhakta|Uselman/i.test(blob), false);
});

